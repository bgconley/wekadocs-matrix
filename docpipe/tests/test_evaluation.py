import json
from pathlib import Path

import pytest

from docpipe.evaluation import evaluate_corpus

GOOD_MD = """---
title: Eval Doc
version: "7.5"
---

# Eval Doc

## Procedure

Step 1: Check the cluster.

```bash
ncli cluster get
```

Step 2: Review the output.

| Command | Purpose |
|---|---|
| ncli cluster get | Inspect the cluster |
"""


def _write(root: Path, name: str, text: str) -> Path:
    path = root / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def test_eval_runs_reference_free_contract_baseline_and_boilerplate_checks(tmp_path):
    _write(tmp_path, "good.md", GOOD_MD)
    _write(tmp_path, "leaky.md", GOOD_MD + "\nGenerated by WeasyPrint\n")

    report = evaluate_corpus(tmp_path)

    assert report.total > 0
    assert report.tier0_pass_rate == pytest.approx(1.0)
    assert report.boilerplate_leaks == 1
    assert any(
        result.type == "absence" and not result.passed for result in report.case_results
    )


def test_eval_applies_machine_checkable_spec_cases(tmp_path):
    _write(tmp_path, "good.md", GOOD_MD)
    spec = {
        "tests": [
            {
                "id": "presence-cli",
                "path": "good.md",
                "type": "presence",
                "text": "ncli cluster get",
            },
            {
                "id": "absence-boilerplate",
                "path": "good.md",
                "type": "absence",
                "text": "Generated by WeasyPrint",
            },
            {
                "id": "reading-order",
                "path": "good.md",
                "type": "reading_order",
                "before": "Step 1",
                "after": "Step 2",
            },
            {"id": "table", "path": "good.md", "type": "table_rectangular"},
            {"id": "contract", "path": "good.md", "type": "contract"},
            {"id": "baseline", "path": "good.md", "type": "baseline"},
        ]
    }
    spec_path = tmp_path / "eval_spec.json"
    spec_path.write_text(json.dumps(spec), encoding="utf-8")

    report = evaluate_corpus(tmp_path, spec_path)

    assert report.total == 6
    assert report.pass_fraction == pytest.approx(1.0)
    assert {result.id for result in report.case_results} == {
        "presence-cli",
        "absence-boilerplate",
        "reading-order",
        "table",
        "contract",
        "baseline",
    }


def test_table_eval_treats_escaped_pipe_as_cell_content(tmp_path):
    _write(
        tmp_path,
        "escaped.md",
        """---
title: Escaped
version: "1"
---

# Escaped

| Documentation | Description |
| :--- | :--- |
| [Release Notes \\| Nutanix Enterprise AI](https://portal.nutanix.com) | Release notes. |
""",
    )

    report = evaluate_corpus(tmp_path)

    table_results = [
        result for result in report.case_results if result.type == "table_rectangular"
    ]
    assert table_results
    assert all(result.passed for result in table_results)


