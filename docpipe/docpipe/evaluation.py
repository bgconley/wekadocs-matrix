"""Offline corpus evaluation harness."""

from __future__ import annotations

import json
import re
import zlib
from dataclasses import dataclass, field
from pathlib import Path

from .contract import validate_contract
from .fences import iter_lines_with_fence_state
from .validate import assess_page

_BOILERPLATE_RE = re.compile(
    r"generated by weasyprint|weasyprint|^\s*page\s+\d+\s*(of\s+\d+)?\s*$",
    re.I | re.MULTILINE,
)
_TABLE_ROW_RE = re.compile(r"^\s*\|.*\|\s*$")
_TABLE_SEP_RE = re.compile(r"^:?-{3,}:?$")


@dataclass(frozen=True)
class EvalCaseResult:
    id: str
    type: str
    path: str
    passed: bool
    message: str = ""


@dataclass
class EvalReport:
    case_results: list[EvalCaseResult] = field(default_factory=list)
    tier0_pass_rate: float = 0.0
    boilerplate_leaks: int = 0
    table_validity_rate: float | None = None
    text_layer_recall_mean: float | None = None
    text_layer_recall_min: float | None = None

    @property
    def total(self) -> int:
        return len(self.case_results)

    @property
    def passed(self) -> int:
        return sum(1 for result in self.case_results if result.passed)

    @property
    def pass_fraction(self) -> float:
        return self.passed / self.total if self.total else 1.0

    def to_dict(self) -> dict:
        return {
            "pass_fraction": self.pass_fraction,
            "passed": self.passed,
            "total": self.total,
            "metrics": {
                "tier0_pass_rate": self.tier0_pass_rate,
                "boilerplate_leaks": self.boilerplate_leaks,
                "table_validity_rate": self.table_validity_rate,
                "text_layer_recall_mean": self.text_layer_recall_mean,
                "text_layer_recall_min": self.text_layer_recall_min,
            },
            "cases": [result.__dict__ for result in self.case_results],
        }


def evaluate_corpus(root: Path, spec_path: Path | None = None) -> EvalReport:
    root = Path(root)
    cases = (
        _load_spec_cases(spec_path) if spec_path is not None else _default_cases(root)
    )
    results = [_run_case(root, case) for case in cases]
    return _build_report(results)


def _load_spec_cases(spec_path: Path) -> list[dict]:
    data = json.loads(Path(spec_path).read_text(encoding="utf-8"))
    raw_cases = data.get("tests", [])
    if not isinstance(raw_cases, list):
        raise ValueError("eval spec must contain a 'tests' list")
    return [case for case in raw_cases if isinstance(case, dict)]


def _default_cases(root: Path) -> list[dict]:
    cases: list[dict] = []
    for path in sorted(root.rglob("*.md")):
        rel = path.relative_to(root).as_posix()
        cases.extend(
            [
                {"id": f"contract:{rel}", "path": rel, "type": "contract"},
                {"id": f"baseline:{rel}", "path": rel, "type": "baseline"},
                {
                    "id": f"absence:boilerplate:{rel}",
                    "path": rel,
                    "type": "absence",
                    "regex": _BOILERPLATE_RE.pattern,
                },
            ]
        )
        text = path.read_text(encoding="utf-8")
        if _has_table_candidate(text):
            cases.append(
                {
                    "id": f"table_rectangular:{rel}",
                    "path": rel,
                    "type": "table_rectangular",
                }
            )
    return cases


def _build_report(results: list[EvalCaseResult]) -> EvalReport:
    contract_cases = [result for result in results if result.type == "contract"]
    table_cases = [result for result in results if result.type == "table_rectangular"]
    boilerplate_leaks = sum(
        1
        for result in results
        if result.type == "absence" and "boilerplate" in result.id and not result.passed
    )
    return EvalReport(
        case_results=results,
        tier0_pass_rate=_rate(contract_cases),
        boilerplate_leaks=boilerplate_leaks,
        table_validity_rate=_rate(table_cases) if table_cases else None,
    )


def _rate(results: list[EvalCaseResult]) -> float:
    if not results:
        return 1.0
    return sum(1 for result in results if result.passed) / len(results)


def _run_case(root: Path, case: dict) -> EvalCaseResult:
    case_type = _normalize_type(str(case.get("type", "")))
    case_id = str(case.get("id") or f"{case_type}:{case.get('path', '')}")
    rel_path = str(case.get("path", ""))
    path = root / rel_path
    if not rel_path:
        return EvalCaseResult(case_id, case_type, rel_path, False, "missing path")
    if not path.is_file():
        return EvalCaseResult(case_id, case_type, rel_path, False, "file not found")
    text = path.read_text(encoding="utf-8")

    if case_type == "presence":
        needle = str(case.get("text", ""))
        passed = bool(needle) and needle in text
        message = "present" if passed else f"missing text: {needle}"
    elif case_type == "absence":
        pattern = case.get("regex")
        if pattern is not None:
            matched = re.search(str(pattern), text, re.I | re.MULTILINE) is not None
            label = str(pattern)
        else:
            needle = str(case.get("text", ""))
            matched = bool(needle) and needle in text
            label = needle
        passed = not matched
        message = "absent" if passed else f"forbidden text found: {label}"
    elif case_type == "reading_order":
        before = str(case.get("before", ""))
        after = str(case.get("after", ""))
        before_at = text.find(before)
        after_at = text.find(after)
        passed = bool(before and after) and 0 <= before_at < after_at
        message = "ordered" if passed else "expected before/after order not found"
    elif case_type == "table_rectangular":
        passed, message = _tables_rectangular(text)
    elif case_type == "contract":
        result = validate_contract(text)
        passed = result.ok
        message = (
            "contract ok"
            if passed
            else ", ".join(violation.code for violation in result.violations)
        )
    elif case_type == "baseline":
        passed, message = _baseline_ok(text)
    else:
        passed = False
        message = f"unknown eval case type: {case_type}"

    return EvalCaseResult(case_id, case_type, rel_path, passed, message)


def _normalize_type(raw: str) -> str:
    normalized = raw.strip().lower().replace("-", "_")
    aliases = {
        "text_presence": "presence",
        "text_absence": "absence",
        "natural_reading_order": "reading_order",
        "table_accuracy": "table_rectangular",
        "baseline_robustness": "baseline",
    }
    return aliases.get(normalized, normalized)


def _has_table_candidate(text: str) -> bool:
    return any(
        _TABLE_ROW_RE.match(line)
        for line, in_fence in iter_lines_with_fence_state(text)
        if not in_fence
    )


def _tables_rectangular(text: str) -> tuple[bool, str]:
    tables = _table_blocks(text)
    if not tables:
        return False, "no GFM table found"
    for table in tables:
        rows = [_split_table_row(line) for line in table]
        widths = {len(row) for row in rows}
        if len(widths) != 1:
            return False, "table rows have inconsistent cell counts"
        if len(rows) < 2 or not all(_TABLE_SEP_RE.match(cell) for cell in rows[1]):
            return False, "table is missing a GFM separator row"
    return True, "tables rectangular"


def _table_blocks(text: str) -> list[list[str]]:
    tables: list[list[str]] = []
    current: list[str] = []

    def flush() -> None:
        nonlocal current
        if len(current) >= 2:
            tables.append(current)
        current = []

    for line, in_fence in iter_lines_with_fence_state(text):
        if not in_fence and _TABLE_ROW_RE.match(line):
            current.append(line)
        elif current:
            flush()
    if current:
        flush()
    return tables


def _split_table_row(line: str) -> list[str]:
    stripped = line.strip()
    if stripped.startswith("|"):
        stripped = stripped[1:]
    if stripped.endswith("|"):
        stripped = stripped[:-1]
    cells: list[str] = []
    current: list[str] = []
    for index, char in enumerate(stripped):
        if char == "|" and (index == 0 or stripped[index - 1] != "\\"):
            cells.append("".join(current).strip())
            current = []
        else:
            current.append(char)
    cells.append("".join(current).strip())
    return cells


def _baseline_ok(text: str) -> tuple[bool, str]:
    flags = list(assess_page(text).flags)
    raw = text.encode("utf-8")
    compressed_len = max(len(zlib.compress(raw)), 1)
    if len(raw) > 1000 and len(raw) / compressed_len > 18:
        flags.append("garbled:compression")
    if any(len(line) > 2000 for line in text.splitlines()):
        flags.append("garbled:long_line")
    if _has_intraline_loop(text):
        flags.append("garbled:intraline_loop")
    if flags:
        return False, ", ".join(flags)
    return True, "baseline ok"


def _has_intraline_loop(text: str) -> bool:
    for line in text.splitlines():
        words = re.findall(r"[A-Za-z0-9]{2,}", line.lower())
        run_word = None
        run_len = 0
        for word in words:
            if word == run_word:
                run_len += 1
            else:
                run_word = word
                run_len = 1
            if run_len >= 8:
                return True
    return False
